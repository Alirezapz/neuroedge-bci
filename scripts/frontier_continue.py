"""Resume an archived frontier run only after exact data-cache reconstruction.

Never changes frozen manifests or accepts numerically different cached data.
For another platform whose regenerated bytes differ, use a new named run.
"""
from pathlib import Path
import argparse
import copy
import json
import shutil

from neuroedge.config import environment,json_write,sha256
from neuroedge.frontier import select,confirm
from neuroedge.frontier_alignment import prepare_rest,load_rest
from neuroedge.frontier_data import prepare_cohort,load_cohort
from neuroedge.frontier_protocol import load_plan,freeze


def restore_cohort(plan,role,subjects):
    root=Path(plan['_root']);out=root/plan['output_dir']
    manifest_path=out/role/'manifest.json'
    if not manifest_path.exists():
        return None
    old=json.loads(manifest_path.read_text())
    if any(not (root/item['path']).exists() for item in old['files'].values()):
        temporary=copy.deepcopy(plan)
        temporary['output_dir']=plan['output_dir']+'_recovery_data'
        rebuilt=prepare_cohort(temporary,subjects,role)
        for name,item in old['files'].items():
            current=rebuilt.manifest['files'][name]
            if current['sha256']!=item['sha256']:
                raise RuntimeError(f'Reconstructed {role}/{name} differs from frozen data. Preserve this run; create a fresh reproduction rather than bypassing the identity guard.')
        for name,item in old['files'].items():
            target=root/item['path'];source=root/rebuilt.manifest['files'][name]['path']
            if source!=target:
                if target.exists():
                    raise RuntimeError('Do not replace an existing frozen data file.')
                target.parent.mkdir(parents=True,exist_ok=True)
                shutil.copyfile(source,target)
        print('Exact frozen task data restored:',role,flush=True)
    cohort=load_cohort(plan,role)
    rest_manifest=out/role/'rest_manifest.json'
    if rest_manifest.exists():
        rest=json.loads(rest_manifest.read_text())
        if not (root/rest['path']).exists():
            temporary=copy.deepcopy(plan);temporary['output_dir']=plan['output_dir']+'_recovery_data'
            prepare_rest(temporary,cohort,role)
            rebuilt=json.loads((root/temporary['output_dir']/role/'rest_manifest.json').read_text())
            if rebuilt['sha256']!=rest['sha256']:
                raise RuntimeError('Reconstructed resting references differ. Do not bypass the frozen identity.')
            target=root/rest['path'];source=root/rebuilt['path']
            if source!=target:
                target.parent.mkdir(parents=True,exist_ok=True)
                shutil.copyfile(source,target)
        load_rest(plan,cohort,role)
    return cohort


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--plan',default='configs/frontier.yaml')
    args=parser.parse_args();plan=load_plan(args.plan)
    out,identity=freeze(plan)
    restore_cohort(plan,'development_data',plan['discovery_subjects']+plan['validation_subjects'])
    json_write(out/'resumed_environment.json',environment())
    select(plan)
    anchor=out/'selection_observed_before_reset.json'
    if anchor.exists():
        expected='2e98bfdccb7649590f628b60b88a7768980f62296f897fe31ba3ada25edda3d7'
        if sha256(anchor)!=expected or sha256(out/'selection.json')!=expected:
            raise RuntimeError('Recovered selection differs from the selection recorded before reset. Investigate before acquiring or evaluating confirmation data.')
        json_write(out/'selection_recovery_check.json',{'status':'PASS','selection_sha256':expected,
            'protocol_sha256':identity['sha256'],'same_frozen_selection_as_before_runtime_reset':True})
    if (out/'confirmation_data/manifest.json').exists():
        restore_cohort(plan,'confirmation_data',plan['confirmation_subjects'])
    confirm(plan)
    from neuroedge.frontier_verify import verify
    from neuroedge.frontier_report import report
    verify(plan)
    report(plan)


if __name__=='__main__':main()
